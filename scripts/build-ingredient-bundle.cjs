'use strict';
const fs = require('node:fs');
const path = require('node:path');
const { execFileSync } = require('node:child_process');

const root = path.resolve(__dirname, '..');
const loaderPath = path.join(root, 'ingredient-loader.js');
const outDir = path.join(root, 'dist');
const outPath = path.join(outDir, 'ingredients-bundle.js');

function extractMods(loaderSource) {
  const match = loaderSource.match(/mods=(\[[^\]]+\])/);
  if (!match) {
    throw new Error('Could not find mods=[...] array in ingredient-loader.js');
  }
  const mods = JSON.parse(match[1]);
  if (!Array.isArray(mods) || mods.length === 0) {
    throw new Error('Extracted mods list is empty');
  }
  return mods;
}

function buildBundle() {
  const loaderSource = fs.readFileSync(loaderPath, 'utf8');
  const mods = extractMods(loaderSource);
  const chunks = [
    '/* Auto-generated by scripts/build-ingredient-bundle.cjs — do not edit manually */'
  ];

  for (const mod of mods) {
    const filePath = path.join(root, mod);
    if (!fs.existsSync(filePath)) {
      throw new Error(`Missing module listed in ingredient-loader.js: ${mod}`);
    }
    const content = fs.readFileSync(filePath, 'utf8').trim();
    chunks.push(`\n/* --- ${mod} --- */\n${content}\n;`);
  }

  fs.mkdirSync(outDir, { recursive: true });
  const bundle = chunks.join('\n');
  fs.writeFileSync(outPath, bundle, 'utf8');
  execFileSync(process.execPath, ['--check', outPath], { stdio: 'pipe' });
  return { count: mods.length, bytes: Buffer.byteLength(bundle, 'utf8'), outPath };
}

if (require.main === module) {
  const result = buildBundle();
  console.log(`Built dist/ingredients-bundle.js (${result.count} modules, ${result.bytes} bytes)`);
}

module.exports = { extractMods, buildBundle };
